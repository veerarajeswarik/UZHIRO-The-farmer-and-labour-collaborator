const mongoose = require('mongoose');

const TASK_TYPES = ['Planting', 'Irrigation', 'Fertilizer', 'Pest Monitoring', 'Harvest', 'General'];
const STATUSES = ['Pending', 'Completed'];

const farmTaskSchema = new mongoose.Schema(
  {
    farmer: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true, index: true },
    title: { type: String, required: true, trim: true, maxlength: 150 },
    type: { type: String, enum: TASK_TYPES, required: true },
    crop: { type: mongoose.Schema.Types.ObjectId, ref: 'Crop', default: null },
    dueDate: { type: Date, required: true },
    notes: { type: String, trim: true, maxlength: 500 },

    status: { type: String, enum: STATUSES, default: 'Pending', index: true },
    completedAt: { type: Date, default: null },

    // True for tasks created via generate-from-crop rather than typed in by hand.
    isAutoGenerated: { type: Boolean, default: false },
  },
  { timestamps: true }
);

farmTaskSchema.index({ farmer: 1, dueDate: 1 });

module.exports = mongoose.model('FarmTask', farmTaskSchema);
module.exports.TASK_TYPES = TASK_TYPES;
module.exports.STATUSES = STATUSES;
