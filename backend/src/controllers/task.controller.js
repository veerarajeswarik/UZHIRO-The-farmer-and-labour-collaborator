const asyncHandler = require('express-async-handler');
const FarmTask = require('../models/FarmTask');
const Crop = require('../models/Crop');
const { sendSuccess, sendError } = require('../utils/apiResponse');

function serialize(task) {
  return {
    id: task._id,
    title: task.title,
    type: task.type,
    crop: task.crop ? { id: task.crop._id || task.crop, name: task.crop.name } : null,
    dueDate: task.dueDate,
    notes: task.notes || '',
    status: task.status,
    completedAt: task.completedAt,
    isAutoGenerated: task.isAutoGenerated,
    createdAt: task.createdAt,
  };
}

// POST /api/tasks (protected, farmer only)
const createTask = asyncHandler(async (req, res) => {
  const { title, type, dueDate, notes, cropId } = req.body;
  const task = await FarmTask.create({
    farmer: req.user._id,
    title,
    type,
    dueDate,
    notes,
    crop: cropId || null,
  });
  const populated = await task.populate('crop', 'name');
  sendSuccess(res, 201, { task: serialize(populated) });
});

// GET /api/tasks?status=&type=&cropId=&upcoming=true (protected, farmer only)
const listTasks = asyncHandler(async (req, res) => {
  const filter = { farmer: req.user._id };
  if (req.query.status) filter.status = req.query.status;
  if (req.query.type) filter.type = req.query.type;
  if (req.query.cropId) filter.crop = req.query.cropId;
  if (req.query.upcoming === 'true') {
    filter.dueDate = { $gte: new Date(new Date().toDateString()) };
    filter.status = filter.status || 'Pending';
  }

  const tasks = await FarmTask.find(filter).sort({ dueDate: 1 }).populate('crop', 'name');
  sendSuccess(res, 200, { tasks: tasks.map(serialize), count: tasks.length });
});

async function findOwnTask(taskId, farmerId) {
  return FarmTask.findOne({ _id: taskId, farmer: farmerId }).populate('crop', 'name');
}

// PUT /api/tasks/:id (protected, owner only)
const updateTask = asyncHandler(async (req, res) => {
  const task = await findOwnTask(req.params.id, req.user._id);
  if (!task) return sendError(res, 404, 'Task not found.');

  const allowedFields = ['title', 'type', 'dueDate', 'notes'];
  for (const field of allowedFields) {
    if (req.body[field] !== undefined) task[field] = req.body[field];
  }
  if (req.body.cropId !== undefined) task.crop = req.body.cropId || null;
  if (req.body.status !== undefined) {
    task.status = req.body.status;
    task.completedAt = req.body.status === 'Completed' ? new Date() : null;
  }

  await task.save();
  sendSuccess(res, 200, { task: serialize(task) });
});

// PUT /api/tasks/:id/complete (protected, owner only)
const completeTask = asyncHandler(async (req, res) => {
  const task = await findOwnTask(req.params.id, req.user._id);
  if (!task) return sendError(res, 404, 'Task not found.');

  task.status = 'Completed';
  task.completedAt = new Date();
  await task.save();
  sendSuccess(res, 200, { task: serialize(task) });
});

// DELETE /api/tasks/:id (protected, owner only)
const deleteTask = asyncHandler(async (req, res) => {
  const task = await FarmTask.findOneAndDelete({ _id: req.params.id, farmer: req.user._id });
  if (!task) return sendError(res, 404, 'Task not found.');
  sendSuccess(res, 200, { deleted: true });
});

// Best-effort keyword mapping from a cultivation stage name to a task type.
// Falls back to 'General' rather than guessing wrong.
function inferTaskType(stageName) {
  const s = stageName.toLowerCase();
  if (/(harvest|picking|maturation)/.test(s)) return 'Harvest';
  if (/(sow|sowing|planting|transplant|nursery)/.test(s)) return 'Planting';
  if (/(irrigat|water|flood)/.test(s)) return 'Irrigation';
  if (/(fertiliz|nutrient|manure|top-dress|topdress)/.test(s)) return 'Fertilizer';
  if (/(pest|disease|pegging|blight|borer)/.test(s)) return 'Pest Monitoring';
  return 'General';
}

/**
 * POST /api/tasks/generate-from-crop (protected, farmer only)
 * Body: { cropId, plantingDate }
 *
 * Creates one task per the crop's real cultivation stages, spaced evenly
 * across its real cultivationDurationDays starting at plantingDate. This
 * distributes real crop data (stage count + total duration) rather than
 * inventing per-stage timing we don't have - every generated task is
 * flagged isAutoGenerated and noted as an approximate starting point.
 */
const generateFromCrop = asyncHandler(async (req, res) => {
  const { cropId, plantingDate } = req.body;
  const crop = await Crop.findById(cropId);
  if (!crop) return sendError(res, 404, 'Crop not found.');
  if (!crop.cultivationStages || crop.cultivationStages.length === 0) {
    return sendError(res, 400, 'No cultivation stage data available for this crop yet.');
  }

  const planting = new Date(plantingDate);
  const stageCount = crop.cultivationStages.length;

  const tasksToCreate = crop.cultivationStages.map((stage, i) => {
    const offsetDays = stageCount > 1 ? Math.round((i / (stageCount - 1)) * crop.cultivationDurationDays) : 0;
    const dueDate = new Date(planting);
    dueDate.setDate(dueDate.getDate() + offsetDays);

    return {
      farmer: req.user._id,
      title: `${crop.name}: ${stage.stage}`,
      type: inferTaskType(stage.stage),
      crop: crop._id,
      dueDate,
      notes: `${stage.description} (Auto-generated from typical cultivation stages - approximate timing based on a ${crop.cultivationDurationDays}-day duration; adjust for your field conditions.)`,
      isAutoGenerated: true,
    };
  });

  const created = await FarmTask.insertMany(tasksToCreate);
  const populated = await FarmTask.find({ _id: { $in: created.map((t) => t._id) } })
    .sort({ dueDate: 1 })
    .populate('crop', 'name');

  sendSuccess(res, 201, {
    tasks: populated.map(serialize),
    count: populated.length,
    disclaimer:
      'These dates are evenly spaced across the crop\'s typical total duration, not precise agronomic timing - review and adjust each task for your actual field conditions.',
  });
});

module.exports = { createTask, listTasks, updateTask, completeTask, deleteTask, generateFromCrop };
